/** Renders specs/001-oscurapdf/ner-eval-report.md from the evaluation results. */
import { recallRate, tierOf, type EvalCategory, type Recall } from './metrics';
import type { PrecisionScore } from './precision';

export type Language = 'it' | 'en';
export type RecallTable = Record<Language, Record<EvalCategory, Recall>>;

export interface EvalResults {
  readonly shown: RecallTable;
  readonly preselected: RecallTable;
  readonly precision: ReadonlyArray<{ readonly name: string; readonly score: PrecisionScore }>;
  readonly rules: Readonly<Record<'EMAIL' | 'IBAN' | 'PAYMENT_CARD', number>>;
  readonly millis: number;
}

const CATEGORIES: readonly EvalCategory[] = ['PERSON', 'LOCATION', 'ORGANIZATION'];
const pct = (value: number): string => `${(value * 100).toFixed(1)}%`;
const ratio = (a: number, b: number): number => (b === 0 ? 1 : a / b);

const total = (table: RecallTable, category: EvalCategory): Recall =>
  (['it', 'en'] as const).map((l) => table[l][category]).reduce((a, b) => ({ found: a.found + b.found, total: a.total + b.total }));

const precisionTotals = (results: EvalResults) =>
  results.precision.reduce(
    (acc, { score }) => ({ correct: acc.correct + score.preselected.correct, total: acc.total + score.preselected.total, fp: acc.fp + score.shown.total - score.shown.correct }),
    { correct: 0, total: 0, fp: 0 },
  );

const precisionSection = (results: EvalResults): string[] => [
  '## SC-006b: precision on realistic documents (target: ≥ 95% of preselected suggestions are personal data)',
  '',
  'Corpus: `tools/ner-eval/precision-corpus.ts` — an ID card, a contract, an invoice, a business letter, an employee data sheet, meeting minutes full of surnames, an attendance register, a medical report (the identity of the patient is marked, the clinical content is not), and a report with no personal data at all (IT + EN).',
  '',
  '| Document | Preselected correct | Shown correct | Marked items covered | False positives |',
  '|---|---|---|---|---|',
  ...results.precision.map(({ name, score }) =>
    `| ${name} | ${score.preselected.correct}/${score.preselected.total} | ${score.shown.correct}/${score.shown.total} | ${score.covered.found}/${score.covered.total} | ${score.falsePositives.join(', ') || '—'} |`),
];

const recallSection = (results: EvalResults): string[] => [
  '## SC-006a: PERSON recall on the sentence corpus',
  '',
  'Corpus: `tools/ner-eval/corpus/*.jsonl` (synthetic, 160 IT + 160 EN sentences). "Shown" = proposed at any confidence; "preselected" = High.',
  '',
  '| Language | Category | Shown | Preselected |',
  '|---|---|---|---|',
  ...(['it', 'en'] as const).flatMap((l) =>
    CATEGORIES.map((c) => `| ${l.toUpperCase()} | ${c} | ${pct(recallRate(results.shown[l][c]))} | ${pct(recallRate(results.preselected[l][c]))} |`)),
  '',
  'LOCATION and ORGANIZATION are informational only. Places are suggested only as addresses or labelled',
  'birth/residence places (2026-10-01). Organizations are suggested since 2026-10-04: preselected when a legal form',
  'or an institution head word gives deterministic evidence, shown but not preselected when only the model finds them.',
];

export const renderReport = (results: EvalResults): { text: string; tier: string } => {
  const person = recallRate(total(results.shown, 'PERSON'));
  const totals = precisionTotals(results);
  const precision = ratio(totals.correct, totals.total);
  const tier = tierOf(person, precision);
  const text = [
    '# Detection evaluation report (SC-006, SC-006a, SC-006b)',
    '',
    `Generated by \`npm run eval:ner\` on ${new Date().toISOString().slice(0, 10)} with the pinned on-device model (research R4).`,
    '',
    `**Precision of preselected suggestions**: ${pct(precision)} (${totals.correct}/${totals.total}; target ≥ 95%) — false positives shown in total: ${totals.fp}  `,
    `**PERSON recall**: ${pct(person)} (target ≥ 95%, accepted minimum ≥ 85%)  `,
    `**Tier**: \`${tier}\``,
    '',
    ...precisionSection(results),
    '',
    ...recallSection(results),
    '',
    '## SC-006: well-formed identifiers reported as High (target ≥ 95%)',
    '',
    `| EMAIL | IBAN | PAYMENT_CARD |\n|---|---|---|\n| ${pct(results.rules.EMAIL)} | ${pct(results.rules.IBAN)} | ${pct(results.rules.PAYMENT_CARD)} |`,
    '',
    '## SC-001 NER budget',
    '',
    `Warm detection (rules + model) on \`ten-pages.pdf\`: **${results.millis} ms** in Node (CPU; budget < 5,000 ms).`,
    '',
    '## Caveats',
    '',
    '- Both corpora are synthetic and were written by the developers who wrote the rules, so the figures are an',
    '  upper bound. Precision and recall on real documents are expected to be lower; a real-world evaluation should follow.',
    '- Dates of birth are not detected automatically; redact them manually.',
    '',
  ].join('\n');
  return { text, tier };
};
